// tool/generate_seed_sql.dart
//
// Reads assets/questions.json (the single source of truth) and writes a
// Postgres seed file: supabase/migrations/0002_seed_questions.sql
//
// Each row is inserted as a single VALUES row so the file is easy to read
// and replay. String fields are escaped by doubling any embedded single
// quotes, which is the standard Postgres/SQL escape for literal strings.

import 'dart:convert';
import 'dart:io';

const _inputPath = 'assets/questions.json';
const _outputPath = 'supabase/migrations/0002_seed_questions.sql';

String sqlEscape(String value) {
  return value.replaceAll("'", "''");
}

@pragma('vm:prefer-inline')
String _requireString(Object? value, [String context = 'value']) {
  if (value is String) return value;
  throw FormatException('Expected a string $context, got $value');
}

@pragma('vm:prefer-inline')
int _requireInt(Object? value, [String context = 'value']) {
  if (value is int) return value;
  throw FormatException('Expected an int $context, got $value');
}

// ---------------------------------------------------------------------------
// JSON parsing is handled by dart:convert to correctly handle nested arrays
// and objects in the question seed.
// ---------------------------------------------------------------------------

List<Map<String, Object?>> _parseQuestions(String jsonText) {
  final decoded = jsonDecode(jsonText);
  if (decoded is! List) {
    throw FormatException('Expected a JSON array at the top level.');
  }

  final questions = <Map<String, Object?>>[];
  for (final item in decoded) {
    if (item is! Map<Object?, Object?>) {
      throw FormatException('Expected a JSON object in the question array.');
    }
    questions.add(item.cast<String, Object?>());
  }
  return questions;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

Future<void> main() async {
  final jsonFile = File(_inputPath);
  if (!jsonFile.existsSync()) {
    throw FormatException('Question seed not found at $_inputPath');
  }

  final jsonText = jsonFile.readAsStringSync();
  final questions = _parseQuestions(jsonText);
  final outDir = Directory('supabase/migrations');
  if (!outDir.existsSync()) {
    outDir.createSync(recursive: true);
  }

  final buffer = StringBuffer();
  buffer.writeln('-- Migration: 0002_seed_questions.sql');
  buffer.writeln('-- Source of truth: assets/questions.json');
  buffer.writeln('-- Generated by: tool/generate_seed_sql.dart');
  buffer.writeln();
  buffer.writeln(
      'INSERT INTO questions (id, subject, syllabus_topic, question_text, '
      'options, correct_option_index, explanation) VALUES');

  for (var i = 0; i < questions.length; i++) {
    final q = questions[i];
    buffer.write('  (');
    buffer.write("'");
    buffer.write(sqlEscape(_requireString(q['id'], 'id')));
    buffer.write("', ");
    buffer.write("'");
    buffer.write(sqlEscape(_requireString(q['subject'], 'subject')));
    buffer.write("', ");
    buffer.write("'");
    buffer.write(sqlEscape(_requireString(q['syllabus_topic'], 'syllabus_topic')));
    buffer.write("', ");
    buffer.write("'");
    buffer.write(sqlEscape(_requireString(q['question_text'], 'question_text')));
    buffer.write("', ARRAY[");
    final options = q['options'] as List;
    for (var j = 0; j < options.length; j++) {
      if (j > 0) buffer.write(', ');
      buffer.write("'");
      buffer.write(sqlEscape(options[j].toString()));
      buffer.write("'");
    }
    buffer.write("], ");
    buffer.write(_requireInt(q['correct_option_index'], 'correct_option_index'));
    buffer.write(", ");
    buffer.write("'");
    buffer.write(sqlEscape(_requireString(q['explanation'], 'explanation')));
    buffer.write("')");
    if (i < questions.length - 1) {
      buffer.writeln(',');
    } else {
      buffer.writeln(';');
    }
  }

  buffer.writeln();
  buffer.writeln('-- End of seed data.');

  await File(_outputPath).writeAsString(buffer.toString());
  print('Wrote ${questions.length} question rows to $_outputPath');
}
